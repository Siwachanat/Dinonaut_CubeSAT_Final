/* Sun sensor model for SUN_ALGORITHM 0: LUT + linear interpolation, 12 points, -50..+60 deg.
   Calibrated 2026-10-06, 10 deg steps. Leave-one-out error max 2.6 deg, rms 1.9 deg.
   Valid for this baffle, this light source and this distance only.
   Pins as wired (SUN_LEFT_PIN 17 / SUN_RIGHT_PIN 16), no pin swap.
   [Team 2026-10-07 evening] Angles are now platform angles: + = CubeSat rotated right
   (SUN_L > SUN_R). The notebook sheet used the opposite sign, so every angle is the
   sheet angle times -1. */
static const float SUN_LUT_NDV[12]   = { -0.15734f, -0.09930f, -0.06448f, -0.04422f, -0.03187f, -0.02107f, -0.00867f, 0.00109f, 0.01198f, 0.02745f, 0.05335f, 0.09425f };
static const float SUN_LUT_ANGLE[12] = { -50.0f, -40.0f, -30.0f, -20.0f, -10.0f, 0.0f, 10.0f, 20.0f, 30.0f, 40.0f, 50.0f, 60.0f };
inline float estimateSunAngle(float ndv) {
  const int n = 12;
  if (ndv <= SUN_LUT_NDV[0])     return SUN_LUT_ANGLE[0];
  if (ndv >= SUN_LUT_NDV[n - 1]) return SUN_LUT_ANGLE[n - 1];
  int i = 1;
  while (i < n - 1 && SUN_LUT_NDV[i] < ndv) ++i;
  float f = (ndv - SUN_LUT_NDV[i - 1]) / (SUN_LUT_NDV[i] - SUN_LUT_NDV[i - 1]);
  return SUN_LUT_ANGLE[i - 1] + f * (SUN_LUT_ANGLE[i] - SUN_LUT_ANGLE[i - 1]);
}
